export function cloneTeam(presetId: string, customIdPrefix?: string): Team {
  const found = PRESET_TEAMS.find((t) => t.id === presetId) || PRESET_TEAMS[0];
  const prefix = customIdPrefix || `team-${Date.now()}`;
  return {
    ...found,
    id: prefix,
    playingXI: found.playingXI.map((p) => ({
      ...p,
      id: `${prefix}-p-${p.jerseyNumber || Math.floor(Math.random() * 1000)}`,
    })),
    substitutes: found.substitutes.map((p) => ({
      ...p,
      id: `${prefix}-sub-${p.jerseyNumber || Math.floor(Math.random() * 1000)}`,
    })),
  };
}
